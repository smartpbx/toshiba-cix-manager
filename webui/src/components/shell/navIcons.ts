// Maps the lucide icon NAMES used by the generated task_tree (tools/task_menu.json)
// and the Home "common jobs" cards to their lucide-react components. Keeping the
// lookup here means the hand-maintained JSON stays declarative — it ships a name,
// not a component. Unknown names fall back to a neutral dot (ChevronRight).
const ICONS: Record<string, LucideIcon> = {
  house: House,
  phone: Phone,
  users: Users,
  hand: Hand,
  zap: Zap,
  "phone-call": PhoneCall,
  "phone-incoming": PhoneIncoming,
  "phone-forwarded": PhoneForwarded,
  layers: Layers,
  moon: Moon,
  route: Route,
  shield: Shield,
  settings: Settings,
  "settings-2": Settings2,
  timer: Timer,
  "sliders-horizontal": SlidersHorizontal,
  cpu: Cpu,
  "list-tree": ListTree,
  history: History,
  search: Search,
  lock: Lock,
  "chevrons-up-down": ChevronsUpDown,
  "chevron-down": ChevronDown,
  "chevron-right": ChevronRight,
  sun: Sun,
  monitor: Monitor,
  voicemail: Voicemail,
  "user-pen": UserPen,
  "git-compare": GitCompare,
  "refresh-cw": RefreshCw,
};

export function navIcon(name: string | undefined): LucideIcon {
  return (name && ICONS[name]) || ChevronRight;
}
